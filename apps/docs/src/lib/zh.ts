export const docsTranslations: Record<string, string> = { ...baseTranslations };
for (const [source, translated] of Object.entries(baseTranslations)) {
  for (const context of contexts) {
    docsTranslations[`${source}(${context})`] = translated;
    docsTranslations[`${source}(${context})(aria-label)`] = translated;
  }
}
